using IndustrialOps.Domain.Common;
using IndustrialOps.Domain.Products;
using IndustrialOps.Domain.ProductionOrders;
using IndustrialOps.Domain.WorkCenters;
using Microsoft.EntityFrameworkCore;

namespace IndustrialOps.Infrastructure.Persistence;

public sealed class AppDbContext(DbContextOptions<AppDbContext> options) : DbContext(options)
{
    public const string OrderNumberSequence = "production_order_number_seq";

    public DbSet<Product> Products => Set<Product>();
    public DbSet<WorkCenter> WorkCenters => Set<WorkCenter>();
    public DbSet<ProductionOrder> ProductionOrders => Set<ProductionOrder>();
    public DbSet<ProductionReport> ProductionReports => Set<ProductionReport>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        // Database sequence used to generate readable order numbers (PO-000001, PO-000002...).
        modelBuilder.HasSequence<long>(OrderNumberSequence).StartsAt(1);

        // Picks up every IEntityTypeConfiguration<T> in this assembly (Configurations folder).
        modelBuilder.ApplyConfigurationsFromAssembly(typeof(AppDbContext).Assembly);

        // Ids are generated by the domain (UUID v7), never by the database. Without this,
        // EF would treat a new child entity with an Id already set (e.g. a ProductionReport
        // added to an order) as an existing row and issue an UPDATE instead of an INSERT.
        foreach (var entityType in modelBuilder.Model.GetEntityTypes()
                     .Where(t => typeof(Entity).IsAssignableFrom(t.ClrType)))
        {
            modelBuilder.Entity(entityType.ClrType).Property(nameof(Entity.Id)).ValueGeneratedNever();
        }
    }
}
